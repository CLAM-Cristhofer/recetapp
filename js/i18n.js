  init() {
    try {
      const saved = localStorage.getItem(this.LANG_KEY);
      this.lang = (saved === 'en' || saved === 'es') ? saved : 'en';
    } catch (e) {
      this.lang = 'en';
    }
    return this.lang;
  },

  getLang() {
    return this.lang;
  },

  setLang(l) {
    if (l !== 'es' && l !== 'en') return;
    this.lang = l;
    try {
      localStorage.setItem(this.LANG_KEY, l);
    } catch (e) {}
  },

  toggle() {
    this.setLang(this.lang === 'es' ? 'en' : 'es');
    return this.lang;
  },

  t(key) {
    const dict = this.STRINGS[this.lang] || this.STRINGS.es;
    return dict[key] !== undefined ? dict[key] : (this.STRINGS.es[key] || key);
  },

  ingredientName(id) {
    const entry = this.INGREDIENT_NAMES[id];
    if (!entry) return id;
    return entry[this.lang] || entry.es;
  }
